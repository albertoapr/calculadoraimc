const { chromium } = require('playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] })
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.hostname !== '127.0.0.1') return route.abort()
    if (url.pathname === '/amplify_outputs.json') return route.fulfill({ json: { custom: { imcApi: { endpoint: 'http://127.0.0.1:5173/mock' } } } })
    if (url.pathname.startsWith('/mock/')) return route.fulfill({ json: { trainers: [], count: 0 } })
    return route.continue()
  })
  await page.addInitScript(() => localStorage.setItem('fitpeso:preferred-city:v1', 'Mesquita'))
  await page.goto('http://127.0.0.1:5173/')
  await page.getByRole('link', { name: 'Entrar', exact: true }).click()
  await page.getByLabel('WhatsApp ou e-mail', { exact: true }).fill('21999999999')
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar pelo WhatsApp', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Alterar', exact: true }).click()
  assert.equal(await page.getByLabel('WhatsApp ou e-mail', { exact: true }).inputValue(), '+5521999999999')
  await page.goto('http://127.0.0.1:5173/')
  await page.getByRole('button', { name: /Buscar Personal/ }).click()
  await page.getByRole('button', { name: /Solicitar Atendimento/ }).click()
  await page.locator('#request-client-age').fill('45')
  await page.getByRole('button', { name: /Continuar/ }).click()
  await page.getByText('Etapa 2 de 4', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Voltar', exact: true }).click()
  assert.equal(await page.locator('#request-client-age').inputValue(), '45')
  await page.goto('http://127.0.0.1:5173/profissionais')
  await page.getByRole('heading', { name: /Profissionais/ }).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  assert.deepEqual(errors, [])
  await browser.close()
  console.log('Browser smoke passed: mobile home, login steps, request steps and age retention, directory; no runtime errors.')
})().catch(error => { console.error(error); process.exit(1) })
